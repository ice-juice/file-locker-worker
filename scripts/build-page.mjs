import * as esbuild from "esbuild";
import fs from "node:fs";

const result = await esbuild.build({
  entryPoints: ["src/download-client.ts"],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: true,
  write: false,
});
const js = result.outputFiles[0].text;
const out = `// Generated by scripts/build-page.mjs. Do not edit.\nexport const PAGE_SCRIPT: string = ${JSON.stringify(js)};\n`;
fs.writeFileSync("src/page-script.ts", out);
console.log(`page script ${js.length} bytes`);